#!/usr/bin/env python3
"""Comment discipline, ported from yi's check_comments.py. A comment earns its line only by
naming what the code cannot: the incident that created a constant or a guard, an invariant the
type system cannot express, or the assurance claim a piece of code is evidence for. Restating a
signature, a name, or the next three statements is none of these.

Three rules, all of them yi's:

- length cap, hard: three lines per comment run, only a licence header may exceed it.
- pointer-only comments, rejected: strip every claim id and wave number and the fact must still
  stand on its own. "C25: see drift.rs" tells a reader without ASSURANCE.md open nothing; ids
  are trailing pointers, never the payload.
- the tag vocabulary is closed. yi's two grants are `Incident:` and `Invariant:`; grid's set is
  its own, read off the tree it already had — those two plus `Claim:` (the assurance row this
  code is evidence for), `Conservatism:` (what the code does when it cannot decide, which is
  the rule the whole engine is built on), `Property:` and `Differential:` (the shape of the
  test that pins it) and `Deterministic:` (why an order is not a contract). Any other
  capitalized `Word:` prefix fails, which is what stops a private dialect accumulating.

Volume outside crates/wire is a shrink-only ratchet. crates/wire is generated by
scripts/gen-wire.py, so its comment volume is the generator's business, not a reviewer's."""
import json, re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from _common import ROOT, BASE, src_files, prod_lines, fail

CAP = 3
LICENSE = re.compile(r"SPDX|Copyright|\bMIT\b|Apache-2\.0|BSD|licen[sc]e", re.I)
GRANTS = {"Incident", "Invariant", "Claim", "Conservatism", "Property", "Differential", "Deterministic"}
TAG = re.compile(r"^//[/!]?\s*([A-Z][a-z]+):")
SIGIL = re.compile(r"^(///|//!|//|/\*+|\*/|\*)\s*")
CODE = re.compile(r"`[^`]*`|\[[^\]]*\]")
# Grid's ids: assurance claims (C1..C43), design decisions (D6), and waves.
ID = re.compile(r"\b[CD]\d{1,3}\b|\bWave \d+\b|\bstage \d\b", re.I)
MIN_WORDS = 8
GENERATED = "wire"


def pointer_only(body):
    """A code span counts as one word — masking it outright called `grid.query.walk` empty."""
    txt = " ".join(SIGIL.sub("", line) for line in body)
    if not ID.search(CODE.sub(" ", txt)):
        return False
    rest = ID.sub(" ", CODE.sub(" span ", txt))
    return len([w for w in re.split(r"[\s.,;:()§—-]+", rest) if w]) < MIN_WORDS


def comment_runs(path):
    runs, cur, in_block = [], None, False
    for i, line in enumerate(prod_lines(path), 1):
        s = line.strip()
        if in_block:
            is_comment = True
            if "*/" in s:
                in_block = False
        elif s.startswith("/*"):
            is_comment = True
            in_block = "*/" not in s
        else:
            is_comment = s.startswith("//")
        if is_comment:
            if cur and cur[1] == i - 1:
                cur[1], cur[2] = i, cur[2] + [s]
            else:
                if cur:
                    runs.append(cur)
                cur = [i, i, [s]]
        elif cur:
            runs.append(cur)
            cur = None
    if cur:
        runs.append(cur)
    return runs


over, volume, tags, pointers = [], 0, [], []
for f in src_files():
    rel = f.relative_to(ROOT)
    generated = rel.parts[1] == GENERATED
    for start, end, body in comment_runs(f):
        n = end - start + 1
        if not generated:
            volume += n
        if generated:
            continue
        if pointer_only(body):
            pointers.append(f"{rel}:{start}: pointer-only comment; state the fact, keep the id a trailing pointer")
        if n > CAP and not (start == 1 and any(LICENSE.search(l) for l in body)):
            over.append(f"{rel}:{start}: comment run of {n} lines > {CAP}")
        m = TAG.match(body[0])
        if m and m.group(1) not in GRANTS:
            tags.append(f"{rel}:{start}: '{m.group(1)}:' is not a grant ({'|'.join(sorted(GRANTS))})")

path = BASE / "comment_budget.json"
base = json.loads(path.read_text())
if "--update" in sys.argv:
    path.write_text(json.dumps({"volume": volume, "over_cap": len(over), "pointers": len(pointers), "tags": len(tags)}, indent=2) + "\n")
    print(f"comments volume {base['volume']} -> {volume}, over_cap {base['over_cap']} -> {len(over)}, "
          f"pointers {base['pointers']} -> {len(pointers)}, tags {base['tags']} -> {len(tags)}")
    sys.exit(0)
errs = []
for name, hits in (("over_cap", over), ("pointers", pointers), ("tags", tags)):
    if len(hits) > base[name]:
        errs += hits + [f"{len(hits)} {name} > budget {base[name]}"]
if volume > base["volume"]:
    errs.append(f"comment volume outside crates/{GENERATED} {volume} > budget {base['volume']}")
fail(errs, f"comments ({volume}/{base['volume']} lines, {len(over)}/{base['over_cap']} over cap, "
           f"{len(pointers)}/{base['pointers']} pointer-only, {len(tags)}/{base['tags']} off-vocabulary)")
